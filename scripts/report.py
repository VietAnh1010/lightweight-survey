def _bibtex_escape(value: str) -> str:
    return value.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def build_bibtex(store: Store) -> str:
    entries = []
    for rec in included(store):
        is_preprint = not rec.get("doi") or (rec.get("venue_short") == "arXiv")
        kind = "misc" if is_preprint else "inproceedings"
        fields = [
            ("title", _bibtex_escape(rec.get("title", ""))),
            ("author", _bibtex_escape(" and ".join(rec.get("authors") or []))),
            ("year", str(rec.get("year") or "")),
        ]
        if not is_preprint:
            fields.append(("booktitle", _bibtex_escape(rec.get("venue", ""))))
        if rec.get("doi"):
            fields.append(("doi", rec["doi"]))
        if rec.get("arxiv_id"):
            fields.append(("eprint", rec["arxiv_id"]))
            fields.append(("archivePrefix", "arXiv"))
        if rec.get("url"):
            fields.append(("url", rec["url"]))

        body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields if v)
        entries.append(f"@{kind}{{{rec['citekey']},\n{body}\n}}")
    header = (
        "% Generated by scripts/report.py from papers/library.jsonl.\n"
        "% Every entry corresponds to a record fetched from a live API.\n\n"
    )
    return header + "\n\n".join(entries) + "\n"


# --------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--stubs", action="store_true",
                    help="also create blank notes for included papers that lack one")
    args = ap.parse_args()

    store = Store()
    assign_citekeys(store)
    store.save()

    REVIEW_DIR.mkdir(parents=True, exist_ok=True)
    if args.stubs:
        log(f"created {write_stubs(store)} note stubs")

    BIB_PATH.write_text(build_bibliography(store), encoding="utf-8")
    TABLE_PATH.write_text(build_table(store), encoding="utf-8")
    BIBTEX_PATH.write_text(build_bibtex(store), encoding="utf-8")

    papers = included(store)
    with_notes = sum(1 for r in papers if note_path(r.get("citekey", "")).exists())
    log(f"wrote {BIB_PATH.name}, {TABLE_PATH.name}, {BIBTEX_PATH.name}")
    log(f"{len(papers)} included papers, {with_notes} with notes")


if __name__ == "__main__":
    main()
