# annotated bibliography
# --------------------------------------------------------------------------

def build_bibliography(store: Store) -> str:
    papers = included(store)
    by_category: dict[str, list[dict]] = defaultdict(list)
    for rec in papers:
        for cat in (rec.get("categories") or categorize(rec)) or ["uncategorized"]:
            by_category[cat].append(rec)

    out = [
        "# Annotated bibliography",
        "",
        f"{len(papers)} included papers. Generated by `scripts/report.py` — "
        "edit the notes in `papers/notes/`, not this file.",
        "",
        "## Contents",
        "",
    ]
    for cat in sorted(by_category):
        out.append(f"- [{cat}](#{cat}) — {len(by_category[cat])}")
    out.append("")

    for cat in sorted(by_category):
        out += [f"## {cat}", ""]
        for rec in by_category[cat]:
            sections = {}
            path = note_path(rec.get("citekey", ""))
            if path.exists():
                sections = parse_note(path)

            out += [
                f"### {rec.get('title', 'Untitled')}",
                "",
                f"`{rec.get('citekey', '')}` · {author_line(rec)} · {venue_line(rec)}"
                + (f" · {rec['cited_by_count']} citations" if rec.get("cited_by_count") else ""),
                "",
            ]
            links = link_line(rec)
            if links:
                out += [links, ""]
            if rec.get("reason"):
                out += [f"**Why included:** {rec['reason']}", ""]

            if sections:
                for name in SECTIONS:
                    body = sections.get(name.lower(), "").strip()
                    if body:
                        out += [f"**{name}.** {body}", ""]
            else:
                out += ["_No note yet._", ""]
    return "\n".join(out)


# --------------------------------------------------------------------------
# comparison table
# --------------------------------------------------------------------------

TABLE_COLUMNS = [
    ("Paper", lambda rec, sec: f"`{rec.get('citekey', '')}`"),
    ("Venue", lambda rec, sec: venue_line(rec)),
    ("Categories", lambda rec, sec: ", ".join(rec.get("categories") or categorize(rec))),
    ("Problem", lambda rec, sec: summarize(sec.get("problem", ""))),
    ("Main idea", lambda rec, sec: summarize(sec.get("main ideas", ""))),
    ("Evaluation", lambda rec, sec: summarize(sec.get("evaluation", ""))),
    ("Limitations", lambda rec, sec: summarize(sec.get("limitations", ""))),
]


def build_table(store: Store) -> str:
    papers = included(store)
    out = [
        "# Cross-paper comparison",
        "",
        f"{len(papers)} included papers, ordered by priority then category. "
        "Every cell is derived from `papers/notes/<citekey>.md`; a blank cell "
        "means the note has not been written yet.",
        "",
        "| " + " | ".join(name for name, _ in TABLE_COLUMNS) + " |",
        "|" + "|".join(["---"] * len(TABLE_COLUMNS)) + "|",
    ]
    for rec in papers:
        path = note_path(rec.get("citekey", ""))
        sections = parse_note(path) if path.exists() else {}
        cells = [render(rec, sections) for _, render in TABLE_COLUMNS]
        out.append("| " + " | ".join(cell or "—" for cell in cells) + " |")

    out += ["", "## Coverage", ""]
    cats = Counter(c for r in papers for c in (r.get("categories") or categorize(r)))
    venues = Counter(r.get("venue_short") or "other" for r in papers)
    years = Counter(r.get("year") for r in papers)
    tiers = Counter(venue_tier(r) for r in papers)

    out += ["| Category | Papers |", "|---|---|"]
    out += [f"| {cat} | {n} |" for cat, n in cats.most_common()]
    out += ["", "| Venue | Papers |", "|---|---|"]
    out += [f"| {venue} | {n} |" for venue, n in venues.most_common()]
    out += ["", "| Year | Papers |", "|---|---|"]
    out += [f"| {year} | {n} |" for year, n in sorted(years.items(), key=lambda kv: kv[0] or 0)]
    out += ["", f"Venue tier: {dict(tiers)}", ""]
    return "\n".join(out)


