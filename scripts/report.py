"""Generate the deliverables from the library and the notes.

Everything here is mechanical — derived entirely from papers/library.jsonl and
papers/notes/*.md. Nothing in these outputs is written from memory, which is
what makes them checkable. The one hand-written document, review/synthesis.md,
is left alone by this script.

    python3 scripts/report.py                 # all outputs
    python3 scripts/report.py --stubs         # create missing note templates
"""

from __future__ import annotations

import argparse
import re
from collections import Counter, defaultdict
from pathlib import Path

from common import LIBRARY, NOTES_DIR, ROOT, Store, assign_citekeys, log, venue_tier
from notes import SECTIONS, note_path, parse_note, summarize, template
from topic import categorize

REVIEW_DIR = ROOT / "review"

BIB_PATH = REVIEW_DIR / "annotated-bibliography.md"
TABLE_PATH = REVIEW_DIR / "comparison-table.md"
BIBTEX_PATH = REVIEW_DIR / "references.bib"


def included(store: Store) -> list[dict]:
    papers = store.by_status("included")
    papers.sort(key=lambda r: (
        -(r.get("priority") or 0),
        sorted(r.get("categories") or categorize(r)),
        -(r.get("cited_by_count") or 0),
    ))
    return papers


def author_line(rec: dict, limit: int = 4) -> str:
    authors = rec.get("authors") or []
    if not authors:
        return "Unknown"
    shown = ", ".join(authors[:limit])
    return shown + (" et al." if len(authors) > limit else "")


def venue_line(rec: dict) -> str:
    venue = rec.get("venue_short") or rec.get("venue") or "?"
    return f"{venue} {rec.get('year', '')}".strip()


def link_line(rec: dict) -> str:
    bits = []
    if rec.get("doi"):
        bits.append(f"[doi](https://doi.org/{rec['doi']})")
    if rec.get("arxiv_id"):
        bits.append(f"[arXiv](https://arxiv.org/abs/{rec['arxiv_id']})")
    if rec.get("pdf_url"):
        bits.append(f"[pdf]({rec['pdf_url']})")
    return " · ".join(bits)


# --------------------------------------------------------------------------
# stubs
# --------------------------------------------------------------------------

def write_stubs(store: Store) -> int:
    """Create a blank note for every included paper that lacks one."""
    NOTES_DIR.mkdir(parents=True, exist_ok=True)
    created = 0
    for rec in included(store):
        path = note_path(rec["citekey"])
        if not path.exists():
            path.write_text(template(rec), encoding="utf-8")
            rec["note_path"] = str(path.relative_to(ROOT))
            created += 1
    store.save()
    return created


